//! Project dependency adaptation for Flutter's official Widget Previewer.
//!
//! The scaffold is a separate Pub root and does not inherit the application's
//! overrides. Only that missing boundary is adapted here; Flutter owns preview
//! discovery, compilation, caching, browser launch and hot reload.

use std::collections::BTreeMap;
use std::ffi::OsString;
use std::fs;
use std::io::Write;
use std::path::Path;

use anyhow::{Context, Result, ensure};
use pl_dev_support::{paths, process};
use serde::{Deserialize, Serialize};
use serde_norway::Value;

#[derive(Default, Deserialize, Serialize)]
struct DependencyOverrides {
    // Pub treats pubspec_overrides.yaml as replacement fields, not a package
    // merge. None and an explicitly empty mapping therefore differ.
    dependency_overrides: Option<BTreeMap<String, Value>>,
}

pub(crate) fn run(args: &[OsString]) -> Result<()> {
    let workspace = paths::workspace_root()?;
    let app = paths::studio_app_dir(&workspace);
    let mut forwarded = vec![OsString::from("widget-preview"), OsString::from("start")];
    forwarded.extend_from_slice(args);
    let display = process::display_command("flutter", &forwarded);
    let mut command = process::path_command("flutter", &forwarded);
    command.current_dir(&app);
    if args.iter().any(|arg| arg == "--help" || arg == "-h") {
        return process::run_checked(&mut command, &display);
    }
    super::ensure_flutter_dependencies_for_build(&workspace, &app)?;
    prepare_overrides(&app)?;
    process::run_resident_checked(&mut command, &display)
}

fn read_overrides(path: &Path) -> Result<DependencyOverrides> {
    let contents = fs::read_to_string(path)
        .with_context(|| format!("failed to read dependency overrides: {}", path.display()))?;
    serde_norway::from_str(&contents)
        .with_context(|| format!("invalid dependency overrides: {}", path.display()))
}

fn prepare_overrides(app: &Path) -> Result<()> {
    let mut overrides = read_overrides(&app.join("pubspec.yaml"))?;
    let local_path = app.join("pubspec_overrides.yaml");
    match fs::metadata(&local_path) {
        Ok(_) => {
            if let Some(local) = read_overrides(&local_path)?.dependency_overrides {
                overrides.dependency_overrides = Some(local);
            }
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error).context("inspect application pubspec_overrides.yaml"),
    }
    for (name, dependency) in overrides
        .dependency_overrides
        .get_or_insert_default()
        .iter_mut()
    {
        // The remaining Pub descriptor is deliberately opaque. In particular,
        // a Git descriptor's nested `path` belongs to that Git repository.
        if let Some(path) = dependency
            .as_mapping_mut()
            .and_then(|map| map.get_mut("path"))
        {
            let source = path
                .as_str()
                .with_context(|| format!("dependency override {name}: path must be a string"))?;
            ensure!(!source.is_empty(), "dependency override {name}: empty path");
            let absolute = std::path::absolute(app.join(source))?;
            *path = Value::String(
                absolute
                    .to_str()
                    .context("dependency override path is not UTF-8")?
                    .to_owned(),
            );
        }
    }
    let cache = app.join(".widget_preview");
    fs::create_dir_all(&cache).context("create official preview cache")?;
    let output = cache.join("pubspec_overrides.yaml");
    let contents = format!(
        "# Generated by cargo xtask preview-gui from the application's Pub overrides.\n{}",
        serde_norway::to_string(&overrides)?
    );
    match fs::read_to_string(&output) {
        Ok(previous) if previous == contents => return Ok(()),
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error).context("read preview dependency overrides"),
    }
    let mut staging = tempfile::NamedTempFile::new_in(&cache)?;
    staging.write_all(contents.as_bytes())?;
    staging
        .persist(&output)
        .context("publish preview dependency overrides")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn preview_root_resolves_the_same_dependencies_and_refreshes_removed_overrides() -> Result<()> {
        let project = tempfile::tempdir()?;
        let app = project.path();
        fs::write(
            app.join("pubspec.yaml"),
            "name: example\ndependency_overrides:\n  local_package:\n    path: packages/local\n  hosted_package: ^2.0.0\n  git_package:\n    git:\n      url: https://example.com/repo.git\n      path: packages/git\n",
        )?;
        prepare_overrides(app)?;
        let output = app.join(".widget_preview/pubspec_overrides.yaml");
        let resolved = read_overrides(&output)?.dependency_overrides.unwrap();
        assert_eq!(
            Path::new(resolved["local_package"]["path"].as_str().unwrap()),
            app.join("packages/local")
        );
        assert_eq!(resolved["hosted_package"], Value::String("^2.0.0".into()));
        assert_eq!(resolved["git_package"]["git"]["path"], "packages/git");
        fs::write(
            app.join("pubspec_overrides.yaml"),
            "dependency_overrides: {}\n",
        )?;
        prepare_overrides(app)?;
        assert!(
            read_overrides(&output)?
                .dependency_overrides
                .unwrap()
                .is_empty()
        );
        Ok(())
    }

    #[test]
    fn invalid_application_override_preserves_previous_preview_configuration() -> Result<()> {
        let project = tempfile::tempdir()?;
        let app = project.path();
        fs::write(app.join("pubspec.yaml"), "name: example\n")?;
        prepare_overrides(app)?;
        let output = app.join(".widget_preview/pubspec_overrides.yaml");
        let previous = fs::read(&output)?;
        fs::write(
            app.join("pubspec_overrides.yaml"),
            "dependency_overrides: [",
        )?;
        assert!(prepare_overrides(app).is_err());
        assert_eq!(fs::read(&output)?, previous);
        Ok(())
    }
}
