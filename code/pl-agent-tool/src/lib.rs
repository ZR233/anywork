//! Independent executable tool contracts.
//!
//! This crate is the single shared path between tool authors and tool hosts:
//! [`ToolDefinition`] carries the author declaration, [`Tool`] is the
//! consumer-side execution contract, and [`ToolHandle`] is the one erased
//! dispatch boundary. Implementation modules are private and never re-export
//! these types from submodules.
//!
//! The optional `typed` feature adds the author-side typed layer ([`typed`]).
//! The optional `macros` feature re-exports the thin author macros
//! `#[tool_args]` and `#[tool]`; both features stay off by default so plain
//! consumers build against `futures`, `serde`, `serde_json`, and `thiserror`
//! only.
//!
//! # Consumer example
//!
//! A host fixes its endpoint type once and consumes any tool through it,
//! without cloning or double erasure:
//!
//! ```
//! use std::error::Error as StdError;
//! use pl_agent_tool::{Tool, ToolDefinition, ToolHandle};
//!
//! struct Echo {
//!     definition: ToolDefinition,
//! }
//!
//! impl Tool for Echo {
//!     type Input = String;
//!     type Context = ();
//!     type Output = String;
//!     type Error = std::convert::Infallible;
//!
//!     fn definition(&self) -> &ToolDefinition {
//!         &self.definition
//!     }
//!
//!     async fn execute(
//!         &self,
//!         input: Self::Input,
//!         _context: Self::Context,
//!     ) -> Result<Self::Output, Self::Error> {
//!         Ok(input)
//!     }
//! }
//!
//! pub async fn invoke<I, C, O, E>(
//!     tool: &ToolHandle<I, C, O, E>,
//!     input: I,
//!     context: C,
//! ) -> Result<O, E>
//! where
//!     I: Send + 'static,
//!     C: Send + 'static,
//!     O: Send + 'static,
//!     E: StdError + Send + Sync + 'static,
//! {
//!     tool.execute(input, context).await
//! }
//!
//! # futures::executor::block_on(async {
//! let handle = ToolHandle::new(Echo {
//!     definition: ToolDefinition::text("echo", "Returns the original text").unwrap(),
//! });
//! let output = invoke(&handle, "hi".to_owned(), ()).await.unwrap();
//! assert_eq!(output, "hi");
//! # });
//! ```
//!
//! [`ToolHandle`] is deliberately not `Clone`:
//!
//! ```compile_fail
//! use pl_agent_tool::ToolHandle;
//!
//! fn assert_clone<T: Clone>() {}
//!
//! fn main() {
//!     assert_clone::<ToolHandle<String, (), (), std::convert::Infallible>>();
//! }
//! ```

