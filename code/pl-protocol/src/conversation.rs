#[cfg(test)]
mod tests {
    use super::*;

    fn batch(placement: ChatPlacement) -> ChatBatch {
        ChatBatch {
            placement,
            entries: Vec::new(),
            before: None,
            current: None,
        }
    }

    #[test]
    fn placement_preserves_the_current_and_continuation_boundaries() {
        let children = ChatScope::Children {
            parent_id: "turn:one".into(),
        };
        let mut initial = batch(ChatPlacement::Set);
        assert!(initial.validate_for(&ChatScope::Main).is_err());
        assert!(initial.validate_for(&children).is_ok());
        initial.current = Some(CurrentProjection::empty(7, ThreadStatus::Idle));
        assert!(initial.validate_for(&ChatScope::Main).is_ok());
        assert!(initial.validate_for(&children).is_err());

        let mut append = batch(ChatPlacement::Append);
        assert!(append.validate_for(&ChatScope::Main).is_err());
        append.current = initial.current;
        assert!(append.validate_for(&ChatScope::Main).is_ok());
        append.before = Some("opaque".into());
        assert!(append.validate_for(&ChatScope::Main).is_err());

        let eof = batch(ChatPlacement::Prepend);
        assert!(eof.validate_for(&ChatScope::Main).is_ok());
        assert!(eof.validate_for(&children).is_ok());
    }

    #[test]
    fn demand_and_encoding_count_the_actual_envelope_not_only_payload() {
        let minimum = batch(ChatPlacement::Prepend).encoded_len().unwrap();
        assert!(
            ReadDemand {
                max_items: 1,
                max_bytes: minimum as u32 - 1,
            }
            .validate(minimum)
            .is_err()
        );
        let mut value = batch(ChatPlacement::Prepend);
        value.entries.push(ChatEntry::Atom(Box::new(ChatAtom {
            id: "one".into(),
            completion_item_id: Some("one".into()),
            completion_seq: Some(1),
            source: ChatSourceId::Input {
                input_id: "one".into(),
            },
            source_state: Some(ChatSourceState {
                source: ChatSourceId::Input {
                    input_id: "one".into(),
                },
                lifecycle: ChatSourceLifecycle::Ended {
                    outcome: ChatTerminalOutcome::Completed,
                },
                started: None,
                ended: None,
            }),
            source_order: None,
            kind: ChatAtomKind::Input,
            delivery: ChatDeliveryKind::Independent,
            lifecycle: ChatAtomLifecycle::Terminal {
                started: None,
                ended: None,
                outcome: ChatTerminalOutcome::Completed,
            },
            turn_id: None,
            attempt_id: None,
            tool: None,
            wait: None,
            text_channel: Some(crate::ThreadTextChannel::User),
            started_at: None,
            finished_at: None,
            content_present: Some(true),
            contents: Vec::new(),
            payload: Some(PayloadData::Inline {
                bytes: "中文🦀".as_bytes().to_vec(),
            }),
        })));
        assert!(value.encoded_len().unwrap() > minimum + "中文🦀".len());
        let round_trip: ChatBatch =
            serde_json::from_slice(&serde_json::to_vec(&value).unwrap()).unwrap();
        assert_eq!(value, round_trip);
        assert!(value.validate_for(&ChatScope::Main).is_err());
        assert!(
            value
                .validate_for(&ChatScope::Children {
                    parent_id: "input-owner".into(),
                })
                .is_ok()
        );
    }

    #[test]
    fn member_source_append_is_not_a_main_display_item() {
        let mut value = batch(ChatPlacement::Append);
        value.entries.push(ChatEntry::Source(ChatSourceState {
            source: ChatSourceId::ForegroundTurn {
                turn_id: "turn".into(),
            },
            lifecycle: ChatSourceLifecycle::Active,
            started: Some(ChatFactPosition {
                effect_seq: 4,
                suborder: 0,
            }),
            ended: None,
        }));
        assert!(value.validate_for(&ChatScope::Main).is_err());
        assert!(
            value
                .validate_for(&ChatScope::GroupMembers {
                    reference: TimelineMembersRef {
                        database_id: "database".into(),
                        projection_version: TIMELINE_PROJECTION_VERSION,
                        projection_generation: "generation".into(),
                        item_id: "opaque-group".into(),
                    },
                })
                .is_ok()
        );
        assert_eq!(
            serde_json::from_slice::<ChatBatch>(&serde_json::to_vec(&value).unwrap()).unwrap(),
            value,
        );
    }

    #[test]
    fn main_item_round_trip_keeps_summary_and_versioned_member_scope_without_members() {
        let members = TimelineMembersRef {
            database_id: "database".into(),
            projection_version: TIMELINE_PROJECTION_VERSION,
            projection_generation: "generation".into(),
            item_id: "opaque-group".into(),
        };
        let item = TimelineItem {
            id: members.item_id.clone(),
            kind: TimelineItemKind::WorkGroup,
            source: ChatSourceId::ForegroundTurn {
                turn_id: "turn".into(),
            },
            atom_kind: None,
            delivery: ChatDeliveryKind::Foreground,
            text_channel: None,
            turn_id: Some("turn".into()),
            started_at: None,
            finished_at: None,
            outcome: None,
            summary: Some(TimelineGroupSummary {
                latest_thinking_summary: Some("Reviewing updates".into()),
                member_count: 12_000,
                active_count: 0,
                failed_count: 1,
                cancelled_count: 0,
                categories: vec![TimelineCategoryCount {
                    category: TimelineCategory::Read,
                    count: 12_000,
                }],
                started_at: None,
                finished_at: None,
            }),
            members: Some(members.clone()),
            contents: Vec::new(),
            payload: None,
            content_item_id: None,
            position: Some(3),
            admission_closed: true,
        };
        let mut value = batch(ChatPlacement::Append);
        value.entries.push(ChatEntry::Item(Box::new(item)));
        value.current = Some(CurrentProjection::empty(7, ThreadStatus::Idle));
        assert!(value.validate_for(&ChatScope::Main).is_ok());
        value.current = None;
        assert!(
            value
                .validate_for(&ChatScope::GroupMembers {
                    reference: members.clone(),
                })
                .is_err()
        );
        let encoded = serde_json::to_vec(&value).unwrap();
        let decoded: ChatBatch = serde_json::from_slice(&encoded).unwrap();
        assert_eq!(decoded, value);
        assert!(encoded.len() < 2_048);
        let ChatEntry::Item(item) = &decoded.entries[0] else {
            panic!("Main item changed its entry kind");
        };
        assert_eq!(item.members.as_ref(), Some(&members));
        assert_eq!(item.member_count(), 12_000);
        assert!(item.payload.is_none());

        value.placement = ChatPlacement::Update;
        assert!(value.validate_for(&ChatScope::Main).is_err());
        let ChatEntry::Item(item) = &mut value.entries[0] else {
            unreachable!();
        };
        item.source = ChatSourceId::BackgroundResult {
            message_id: "first-result".into(),
        };
        item.delivery = ChatDeliveryKind::Independent;
        assert!(value.validate_for(&ChatScope::Main).is_ok());
        assert!(
            value
                .validate_for(&ChatScope::GroupMembers {
                    reference: members.clone(),
                })
                .is_err()
        );
        value.before = Some("not-a-header-update".into());
        assert!(value.validate_for(&ChatScope::Main).is_err());
        value.before = None;
        value.current = Some(CurrentProjection::empty(8, ThreadStatus::Idle));
        assert!(value.validate_for(&ChatScope::Main).is_err());
        value.current = None;
        assert_eq!(
            serde_json::from_slice::<ChatBatch>(&serde_json::to_vec(&value).unwrap()).unwrap(),
            value
        );

        let ChatEntry::Item(item) = &mut value.entries[0] else {
            unreachable!();
        };
        item.position = None;
        assert!(value.validate_for(&ChatScope::Main).is_err());
        let ChatEntry::Item(item) = &mut value.entries[0] else {
            unreachable!();
        };
        item.position = Some(3);
        item.summary.as_mut().unwrap().active_count = 1;
        assert!(value.validate_for(&ChatScope::Main).is_err());
    }
}
