#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub enum ChatPlacement {
    Set,
    Prepend,
    Append,
    /// Replace an already loaded background-result group at its stable position.
    /// This updates only the derived header; original completion facts stay immutable.
    Update,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ChatBatch {
    pub placement: ChatPlacement,
    pub entries: Vec<ChatEntry>,
    pub before: Option<String>,
    /// None keeps current unchanged; an explicit snapshot replaces the ordered
    /// current fragments, including an empty list when the live region retires.
    pub current: Option<CurrentProjection>,
}

impl ChatBatch {
    /// 在 Rust 构造/发送边界核验组合，不向 SDK 下放业务切点验证。
    pub fn validate_for(&self, scope: &ChatScope) -> Result<(), StudioError> {
        let placement_valid = match (self.placement, scope) {
            (ChatPlacement::Set, ChatScope::Main) => self.current.is_some(),
            (ChatPlacement::Prepend, ChatScope::Main) => self.current.is_none(),
            (ChatPlacement::Append, ChatScope::Main) => {
                self.before.is_none() && (!self.entries.is_empty() || self.current.is_some())
            }
            (ChatPlacement::Update, ChatScope::Main) => {
                self.before.is_none() && self.current.is_none() && !self.entries.is_empty()
            }
            (
                ChatPlacement::Update,
                ChatScope::GroupMembers { .. } | ChatScope::Children { .. },
            ) => false,
            (ChatPlacement::Set | ChatPlacement::Prepend, ChatScope::GroupMembers { .. }) => {
                self.current.is_none()
            }
            (ChatPlacement::Append, ChatScope::GroupMembers { .. }) => {
                self.before.is_none() && self.current.is_none() && !self.entries.is_empty()
            }
            (ChatPlacement::Set | ChatPlacement::Prepend, ChatScope::Children { .. }) => {
                self.current.is_none()
            }
            (ChatPlacement::Append, ChatScope::Children { .. }) => {
                self.before.is_none() && self.current.is_none() && !self.entries.is_empty()
            }
        };
        let entries_valid = self.entries.iter().all(|entry| match scope {
            ChatScope::Main => matches!(entry, ChatEntry::Item(item)
                if item.position.is_some()
                    && item.admission_closed
                    && (self.placement != ChatPlacement::Update
                        || (item.kind == TimelineItemKind::WorkGroup
                            && item.delivery == ChatDeliveryKind::Independent
                            && matches!(item.source, ChatSourceId::BackgroundResult { .. })))
                    && (item.kind != TimelineItemKind::WorkGroup
                        || (item.summary.as_ref().is_some_and(|summary| summary.active_count == 0)
                            && item.members.as_ref().is_some_and(|members| members.item_id == item.id)))),
            ChatScope::GroupMembers { .. } | ChatScope::Children { .. } => {
                !matches!(entry, ChatEntry::Item(_))
            }
        });
        if !placement_valid || !entries_valid {
            return Err(StudioError::new(
                StudioErrorCode::Internal,
                "Invalid chat placement, continuation or current projection",
                false,
            ));
        }
        Ok(())
    }

    /// HTTP 的规范编码计量；FRB 外层继续核验自己的 Frame 编码上限。
    pub fn encoded_len(&self) -> Result<usize, serde_json::Error> {
        serde_json::to_vec(self).map(|bytes| bytes.len())
    }
}

/// 小 current 与完成切点一起发布，不包含完整 ThreadSnapshot/上下文或增长集合。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct CurrentProjection {
    pub source_effect_seq: u64,
    pub logical_status: ThreadStatus,
    /// 是否存在当前执行来源；持久化 running 不能单独证明这一事实。
    pub execution_present: bool,
    pub active: Option<CurrentActivityHead>,
    pub active_turn: Option<CurrentTurnHead>,
    /// Actual execution source states. These are not presentation boundaries.
    pub sources: Vec<ChatSourceState>,
    /// Ordered current fragments. A WorkGroup/Text/Status item not yet handed to
    /// Main history stays here with a typed, bounded member-query reference.
    #[serde(default)]
    pub items: Vec<TimelineItem>,
    /// Member facts of the current items, including unfinished ones. Clients
    /// index these only through the item's typed member scope.
    pub atoms: Vec<ChatAtom>,
    pub plan: Option<CurrentPlanHead>,
    pub interactions: Option<CurrentCollectionRef>,
    pub previews: Vec<CurrentContentPreview>,
    pub collections: Vec<CurrentCollectionRef>,
}

